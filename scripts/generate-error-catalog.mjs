#!/usr/bin/env node
// generate-error-catalog.mjs —— 从主仓 error-catalog.md 生成 api/errors.md 的
// Coded 目录值域表（M4/M7 同款脚手架，契约仓版；模式对齐 fmby-web
// scripts/generate-error-contract.mjs）。
//
// 思路对齐 #1126 recount：机器可复算取代人肉对账——
//   源 = fmby-v2 `docs/plans/v2-dev/contracts/error-catalog.md`
//        （该表由代码派生，真源 = error_code.rs `as_slug()`/`http_status()`，
//         一致性由主仓单测 `error_catalog_matches_implementation` 锁定）；
//   出 = `api/errors.coded.generated.md`：按 HTTP 分组的 SCREAMING 全量值域表
//        （粘入 api/errors.md「Coded 目录族」节的生成段）。
// ⇒ catalog 长码契约自动跟随，消除「契约值域与 wire 两代并存」整类漂移
//   （实证：errors.md 旧值域表停在前 12 基础类，而 wire 已 201 slug）。
//
// 用法：
//   node scripts/generate-error-catalog.mjs --catalog <error-catalog.md> [--check] [--out <md 路径>]
//     --check  比较生成片段与磁盘现状，不一致 ⇒ rc=1（CI 门模式）
// 退出码：0 = 一致/已写出；1 = --check 不一致；2 = 判据不可用（catalog 缺失/解析失败）

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
const get = (flag) => { const i = args.indexOf(flag); return i >= 0 ? args[i + 1] : undefined; };
const has = (flag) => args.includes(flag);
const catalogPath = get('--catalog');
const outPath = get('--out') || 'api/errors.coded.generated.md';
const checkMode = has('--check');

if (!catalogPath || !existsSync(catalogPath)) {
  console.error(`[ENV] --catalog 缺失或文件不存在: ${catalogPath ?? '(未给)'}`);
  process.exit(2);
}

const src = readFileSync(catalogPath, 'utf8');
// 行格式：| `CODE` | <status> | <message> | <触发条件> | <运维建议> |
const ROW = /^\|\s*`([A-Z][A-Z0-9_]+)`\s*\|\s*(\d{3})\s*\|/;
const rows = [];
for (const line of src.split('\n')) {
  const m = ROW.exec(line);
  if (m) rows.push({ code: m[1], status: Number(m[2]) });
}

if (rows.length === 0) {
  console.error('[FAIL] error-catalog.md 解析出 0 行——表格式漂移，判据不可用');
  process.exit(2);
}

const byStatus = new Map();
for (const r of rows) {
  if (!byStatus.has(r.status)) byStatus.set(r.status, []);
  byStatus.get(r.status).push(r.code);
}
const statuses = [...byStatus.keys()].sort((a, b) => a - b);

const md = `<!-- GENERATED by scripts/generate-error-catalog.mjs —— 请勿手改（源 = fmby-v2 error-catalog.md，主仓单测锁定一致性）。
确定性输出（无时间戳）：--check 以字节比对。行数：${rows.length}。 -->

${statuses
  .map(
    (s) =>
      `**HTTP ${s}**（${byStatus.get(s).length}）：` +
      byStatus
        .get(s)
        .map((c) => `\`${c}\``)
        .join('、'),
  )
  .join('\n\n')}
`;

if (checkMode) {
  const disk = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  const ok = disk === md;
  console.log(ok ? `✅ --check 一致（${rows.length} 码）` : `✗ --check 不一致（磁盘 ${disk.split('\n').length} 行 vs 生成 ${md.split('\n').length} 行）`);
  process.exit(ok ? 0 : 1);
}

writeFileSync(outPath, md);
console.log(`✅ 写出 ${outPath}（${rows.length} 码 / ${statuses.length} 个 HTTP 桶）`);
